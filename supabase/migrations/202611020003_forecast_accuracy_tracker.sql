-- Forecast Accuracy Tracker: save periodic rank forecasts and compare them
-- with the first real ranking sample observed at or shortly after each horizon.

create table if not exists public.chaos_clan_forecast_accuracy (
  id bigint generated by default as identity primary key,
  season_number integer not null,
  forecast_at bigint not null,
  target_at bigint not null,
  horizon_hours smallint not null check (horizon_hours in (1, 6, 24)),
  clan_name text not null,
  predicted_rank smallint not null check (predicted_rank between 1 and 10),
  projected_rep bigint,
  actual_rank smallint check (actual_rank between 1 and 10),
  actual_at bigint,
  evaluated_at bigint,
  absolute_rank_error smallint,
  signed_rank_error smallint,
  evaluation_delay_minutes smallint,
  expired_at bigint,
  created_at bigint not null,
  constraint chaos_clan_forecast_accuracy_unique
    unique (season_number, forecast_at, horizon_hours, clan_name),
  constraint chaos_clan_forecast_accuracy_evaluation_check
    check (
      (evaluated_at is null and actual_rank is null and actual_at is null
        and absolute_rank_error is null and signed_rank_error is null)
      or
      (evaluated_at is not null and actual_rank is not null and actual_at is not null
        and absolute_rank_error is not null and signed_rank_error is not null)
    )
);

create index if not exists chaos_clan_forecast_accuracy_pending_idx
  on public.chaos_clan_forecast_accuracy (season_number, target_at)
  where evaluated_at is null and expired_at is null;

create index if not exists chaos_clan_forecast_accuracy_metrics_idx
  on public.chaos_clan_forecast_accuracy (season_number, horizon_hours, evaluated_at desc)
  where evaluated_at is not null;

create index if not exists chaos_clan_forecast_accuracy_clan_idx
  on public.chaos_clan_forecast_accuracy (season_number, clan_name, horizon_hours, evaluated_at desc)
  where evaluated_at is not null;

alter table public.chaos_clan_forecast_accuracy enable row level security;
revoke all on public.chaos_clan_forecast_accuracy from public, anon, authenticated;
grant all on public.chaos_clan_forecast_accuracy to service_role;

create or replace function public.record_chaos_clan_forecast_accuracy(
  p_season_number integer,
  p_snapshot_at bigint,
  p_forecasts jsonb,
  p_actuals jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_forecast record;
  v_actuals jsonb;
  v_inserted integer := 0;
  v_evaluated integer := 0;
  v_expired integer := 0;
  v_row_count integer := 0;
  v_now bigint;
begin
  if p_season_number is null or p_season_number < 1
     or p_snapshot_at is null or p_snapshot_at < 1
     or jsonb_typeof(p_forecasts) is distinct from 'array'
     or jsonb_typeof(p_actuals) is distinct from 'array'
     or jsonb_array_length(p_forecasts) > 30
     or jsonb_array_length(p_actuals) > 20 then
    raise exception 'Invalid forecast accuracy payload';
  end if;

  v_now := p_snapshot_at;
  v_actuals := p_actuals;

  -- Evaluate with the first actual clan sample at/after the target time,
  -- provided it arrived within a 15-minute tolerance.
  with actual_rows as (
    select lower(trim(a.clan_name)) as clan_key,
           a.actual_rank,
           a.sample_at
      from jsonb_to_recordset(v_actuals)
        as a(clan_name text, actual_rank integer, sample_at bigint)
     where nullif(trim(a.clan_name), '') is not null
       and a.actual_rank between 1 and 10
       and a.sample_at is not null
  ),
  due as (
    select f.id, a.actual_rank, a.sample_at
      from public.chaos_clan_forecast_accuracy f
      join actual_rows a
        on lower(f.clan_name) = a.clan_key
       and a.sample_at >= f.target_at
       and a.sample_at <= f.target_at + 900000
       and a.sample_at <= v_now
     where f.season_number = p_season_number
       and f.evaluated_at is null
       and f.expired_at is null
       and f.target_at <= v_now
  )
  update public.chaos_clan_forecast_accuracy f
     set actual_rank = d.actual_rank,
         actual_at = d.sample_at,
         evaluated_at = d.sample_at,
         absolute_rank_error = abs(f.predicted_rank - d.actual_rank),
         signed_rank_error = f.predicted_rank - d.actual_rank,
         evaluation_delay_minutes = greatest(0, floor((d.sample_at - f.target_at) / 60000.0))::smallint
    from due d
   where f.id = d.id;
  get diagnostics v_evaluated = row_count;

  -- Expire only after the allowed actual-observation window has passed.
  update public.chaos_clan_forecast_accuracy
     set expired_at = v_now
   where season_number = p_season_number
     and evaluated_at is null
     and expired_at is null
     and target_at + 900000 < v_now;
  get diagnostics v_expired = row_count;

  -- Save each forecast window at most once per clan per 30 minutes.
  for v_forecast in
    select *
      from jsonb_to_recordset(p_forecasts)
        as f(horizon_hours integer, clan_name text, predicted_rank integer, projected_rep bigint)
  loop
    if v_forecast.horizon_hours not in (1, 6, 24)
       or nullif(trim(v_forecast.clan_name), '') is null
       or v_forecast.predicted_rank not between 1 and 10 then
      raise exception 'Invalid individual forecast row';
    end if;

    insert into public.chaos_clan_forecast_accuracy (
      season_number, forecast_at, target_at, horizon_hours,
      clan_name, predicted_rank, projected_rep, created_at
    )
    select
      p_season_number,
      v_now,
      v_now + (v_forecast.horizon_hours::bigint * 3600000),
      v_forecast.horizon_hours,
      trim(v_forecast.clan_name),
      v_forecast.predicted_rank,
      v_forecast.projected_rep,
      v_now
    where not exists (
      select 1
        from public.chaos_clan_forecast_accuracy prior
       where prior.season_number = p_season_number
         and prior.horizon_hours = v_forecast.horizon_hours
         and prior.clan_name = trim(v_forecast.clan_name)
         and prior.forecast_at > v_now - 1800000
    )
    on conflict (season_number, forecast_at, horizon_hours, clan_name) do nothing;

    get diagnostics v_row_count = row_count;
    v_inserted := v_inserted + v_row_count;
  end loop;

  -- Keep a bounded 90-day accuracy history; this table is private and compact.
  delete from public.chaos_clan_forecast_accuracy
   where season_number = p_season_number
     and forecast_at < v_now - 90 * 86400000;

  return jsonb_build_object(
    'status', 'ok',
    'forecasts_saved', v_inserted,
    'forecasts_evaluated', v_evaluated,
    'forecasts_expired', v_expired
  );
end;
$$;

create or replace function public.get_chaos_clan_forecast_accuracy(
  p_season_number integer,
  p_days integer default 30
)
returns jsonb
language sql
stable
security invoker
set search_path = public, pg_temp
as $$
  with base as (
    select *
      from public.chaos_clan_forecast_accuracy
     where season_number = p_season_number
       and forecast_at >= (extract(epoch from now()) * 1000)::bigint
           - (least(greatest(coalesce(p_days, 30), 1), 90)::bigint * 86400000)
  ),
  horizon_values as (
    select unnest(array[1,6,24])::smallint as horizon_hours
  ),
  horizon_stats as (
    select horizon_hours,
           count(*) filter (where evaluated_at is not null) as evaluated,
           count(*) filter (where evaluated_at is not null and absolute_rank_error = 0) as exact_matches,
           count(*) filter (where evaluated_at is not null and absolute_rank_error <= 1) as within_one,
           round(avg(absolute_rank_error)::numeric, 2) as mean_absolute_error,
           round(avg(signed_rank_error)::numeric, 2) as mean_signed_error,
           round(avg(evaluation_delay_minutes)::numeric, 1) as mean_evaluation_delay_minutes,
           count(*) filter (where evaluated_at is null and expired_at is null) as pending,
           count(*) filter (where expired_at is not null) as expired
      from base
     group by horizon_hours
  ),
  by_horizon as (
    select jsonb_agg(jsonb_build_object(
      'horizon_hours', h.horizon_hours,
      'evaluated', coalesce(s.evaluated, 0),
      'exact_matches', coalesce(s.exact_matches, 0),
      'within_one', coalesce(s.within_one, 0),
      'exact_accuracy_percent', case when coalesce(s.evaluated,0) > 0
        then round(100.0 * s.exact_matches / s.evaluated, 1) else null end,
      'within_one_percent', case when coalesce(s.evaluated,0) > 0
        then round(100.0 * s.within_one / s.evaluated, 1) else null end,
      'mean_absolute_rank_error', s.mean_absolute_error,
      'mean_signed_rank_error', s.mean_signed_error,
      'mean_evaluation_delay_minutes', s.mean_evaluation_delay_minutes,
      'pending', coalesce(s.pending, 0),
      'expired', coalesce(s.expired, 0),
      'confidence', case when coalesce(s.evaluated,0) >= 50 then 'high'
        when coalesce(s.evaluated,0) >= 20 then 'medium'
        when coalesce(s.evaluated,0) >= 5 then 'early'
        else 'building' end
    ) order by h.horizon_hours) as value
      from horizon_values h
      left join horizon_stats s using (horizon_hours)
  ),
  clan_stats as (
    select clan_name,
           count(*) filter (where evaluated_at is not null) as evaluated,
           round(100.0 * count(*) filter (where evaluated_at is not null and absolute_rank_error = 0)
             / nullif(count(*) filter (where evaluated_at is not null), 0), 1) as exact_accuracy_percent,
           round(100.0 * count(*) filter (where evaluated_at is not null and absolute_rank_error <= 1)
             / nullif(count(*) filter (where evaluated_at is not null), 0), 1) as within_one_percent,
           round(avg(absolute_rank_error)::numeric, 2) as mean_absolute_rank_error,
           round(avg(signed_rank_error)::numeric, 2) as mean_signed_rank_error
      from base
     group by clan_name
  ),
  by_clan as (
    select coalesce(jsonb_agg(jsonb_build_object(
      'clan_name', clan_name,
      'evaluated', evaluated,
      'exact_accuracy_percent', exact_accuracy_percent,
      'within_one_percent', within_one_percent,
      'mean_absolute_rank_error', mean_absolute_rank_error,
      'mean_signed_rank_error', mean_signed_rank_error,
      'confidence', case when evaluated >= 50 then 'high'
        when evaluated >= 20 then 'medium'
        when evaluated >= 5 then 'early'
        else 'building' end
    ) order by mean_absolute_rank_error nulls last, clan_name), '[]'::jsonb) as value
      from clan_stats
  )
  select jsonb_build_object(
    'season_number', p_season_number,
    'window_days', least(greatest(coalesce(p_days, 30), 1), 90),
    'generated_at', (extract(epoch from now()) * 1000)::bigint,
    'by_horizon', coalesce((select value from by_horizon), '[]'::jsonb),
    'by_clan', (select value from by_clan),
    'method', 'Each forecast is evaluated against the first recorded clan ranking sample from its target time through the following 15 minutes.'
  );
$$;

revoke all on function public.record_chaos_clan_forecast_accuracy(integer, bigint, jsonb, jsonb)
  from public, anon, authenticated;
grant execute on function public.record_chaos_clan_forecast_accuracy(integer, bigint, jsonb, jsonb)
  to service_role;

revoke all on function public.get_chaos_clan_forecast_accuracy(integer, integer)
  from public, anon, authenticated;
grant execute on function public.get_chaos_clan_forecast_accuracy(integer, integer)
  to service_role;
