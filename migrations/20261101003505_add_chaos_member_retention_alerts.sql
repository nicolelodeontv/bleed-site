create table if not exists public.chaos_member_retention_alerts (
  id bigint generated by default as identity primary key,
  season_number integer not null,
  member text not null,
  threshold_days integer not null check (threshold_days in (7, 14)),
  last_gain_at bigint,
  inactivity_days integer not null check (inactivity_days >= 0),
  status text not null default 'pending'
    check (status in ('pending', 'sending', 'sent', 'failed')),
  attempt_count integer not null default 0,
  next_attempt_at bigint not null default 0,
  lease_until bigint not null default 0,
  discord_message_id text,
  sent_at bigint,
  last_error text,
  created_at bigint not null,
  updated_at bigint not null,
  constraint chaos_member_retention_alerts_season_member_threshold_key
    unique (season_number, member, threshold_days)
);

create index if not exists chaos_member_retention_alerts_delivery_idx
  on public.chaos_member_retention_alerts (status, next_attempt_at, created_at);

alter table public.chaos_member_retention_alerts enable row level security;
revoke all on public.chaos_member_retention_alerts from public, anon, authenticated;
grant select, insert, update on public.chaos_member_retention_alerts to service_role;
grant usage, select on sequence public.chaos_member_retention_alerts_id_seq to service_role;

create or replace function public.claim_chaos_member_retention_alerts(
  p_now bigint,
  p_limit integer default 30,
  p_lease_ms bigint default 45000
)
returns setof public.chaos_member_retention_alerts
language plpgsql
security invoker
set search_path = pg_catalog, public
as $$
begin
  return query
  with candidates as (
    select id
    from public.chaos_member_retention_alerts
    where (
      (status in ('pending', 'failed') and next_attempt_at <= p_now)
      or (status = 'sending' and lease_until <= p_now)
    )
    order by created_at asc, id asc
    for update skip locked
    limit greatest(1, least(coalesce(p_limit, 30), 50))
  ),
  claimed as (
    update public.chaos_member_retention_alerts as alerts
    set status = 'sending',
        attempt_count = alerts.attempt_count + 1,
        lease_until = p_now + greatest(1000, least(coalesce(p_lease_ms, 45000), 300000)),
        updated_at = p_now
    from candidates
    where alerts.id = candidates.id
    returning alerts.*
  )
  select * from claimed order by id asc;
end;
$$;

revoke all on function public.claim_chaos_member_retention_alerts(bigint, integer, bigint)
  from public, anon, authenticated;
grant execute on function public.claim_chaos_member_retention_alerts(bigint, integer, bigint)
  to service_role;
