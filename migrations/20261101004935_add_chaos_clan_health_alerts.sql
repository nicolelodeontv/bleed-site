CREATE TABLE public.chaos_clan_health_state (
  season_number integer PRIMARY KEY REFERENCES public.chaos_seasons(season_number) ON DELETE CASCADE,
  risk_level text NOT NULL CHECK (risk_level IN ('healthy', 'watch', 'high')),
  score smallint NOT NULL CHECK (score BETWEEN 0 AND 100),
  last_weekly_report_start date,
  updated_at bigint NOT NULL
);

CREATE TABLE public.chaos_clan_health_alerts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_number integer NOT NULL REFERENCES public.chaos_seasons(season_number) ON DELETE CASCADE,
  event_key text NOT NULL,
  event_type text NOT NULL CHECK (event_type IN ('risk_change', 'weekly_summary')),
  payload jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(payload) = 'object'),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sending', 'sent', 'failed')),
  attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
  next_attempt_at bigint NOT NULL DEFAULT 0,
  lease_until bigint NOT NULL DEFAULT 0,
  discord_message_id text,
  sent_at bigint,
  last_error text,
  created_at bigint NOT NULL,
  updated_at bigint NOT NULL,
  CONSTRAINT chaos_clan_health_alerts_season_event_key UNIQUE (season_number, event_key)
);

CREATE INDEX chaos_clan_health_alerts_delivery_idx
  ON public.chaos_clan_health_alerts (status, next_attempt_at, lease_until, created_at);

ALTER TABLE public.chaos_clan_health_state ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.chaos_clan_health_alerts ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.chaos_clan_health_state FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.chaos_clan_health_alerts FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.chaos_clan_health_state TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.chaos_clan_health_alerts TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.chaos_clan_health_alerts_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.queue_chaos_clan_health_alerts(
  p_season_number integer,
  p_risk_level text,
  p_score integer,
  p_payload jsonb,
  p_today date,
  p_week_start date,
  p_week_end date,
  p_now bigint
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_state public.chaos_clan_health_state%ROWTYPE;
  v_seeded boolean := false;
  v_risk_queued boolean := false;
  v_weekly_queued boolean := false;
  v_rows integer := 0;
BEGIN
  IF p_risk_level NOT IN ('healthy', 'watch', 'high') OR
     p_score IS NULL OR p_score < 0 OR p_score > 100 OR
     p_payload IS NULL OR jsonb_typeof(p_payload) <> 'object' THEN
    RAISE EXCEPTION 'invalid clan health alert payload';
  END IF;

  INSERT INTO public.chaos_clan_health_state (
    season_number, risk_level, score, updated_at
  ) VALUES (
    p_season_number, p_risk_level, p_score, p_now
  ) ON CONFLICT (season_number) DO NOTHING;
  GET DIAGNOSTICS v_rows = ROW_COUNT;
  v_seeded := v_rows = 1;

  SELECT * INTO v_state
  FROM public.chaos_clan_health_state
  WHERE season_number = p_season_number
  FOR UPDATE;

  IF NOT v_seeded AND v_state.risk_level <> p_risk_level THEN
    INSERT INTO public.chaos_clan_health_alerts (
      season_number, event_key, event_type, payload,
      status, attempt_count, next_attempt_at, lease_until, created_at, updated_at
    ) VALUES (
      p_season_number,
      'risk-' || p_today::text || '-' || p_risk_level,
      'risk_change',
      p_payload || jsonb_build_object(
        'previous_risk_level', v_state.risk_level,
        'risk_level', p_risk_level,
        'score', p_score
      ),
      'pending', 0, p_now, 0, p_now, p_now
    ) ON CONFLICT (season_number, event_key) DO NOTHING;
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    v_risk_queued := v_rows = 1;
  END IF;

  UPDATE public.chaos_clan_health_state
  SET risk_level = p_risk_level, score = p_score, updated_at = p_now
  WHERE season_number = p_season_number;

  IF p_week_start IS NOT NULL AND p_week_end IS NOT NULL
     AND v_state.last_weekly_report_start IS DISTINCT FROM p_week_start THEN
    INSERT INTO public.chaos_clan_health_alerts (
      season_number, event_key, event_type, payload,
      status, attempt_count, next_attempt_at, lease_until, created_at, updated_at
    ) VALUES (
      p_season_number,
      'weekly-' || p_week_start::text,
      'weekly_summary',
      p_payload || jsonb_build_object(
        'week_start', p_week_start::text,
        'week_end', p_week_end::text
      ),
      'pending', 0, p_now, 0, p_now, p_now
    ) ON CONFLICT (season_number, event_key) DO NOTHING;
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    v_weekly_queued := v_rows = 1;

    UPDATE public.chaos_clan_health_state
    SET last_weekly_report_start = p_week_start, updated_at = p_now
    WHERE season_number = p_season_number;
  END IF;

  RETURN jsonb_build_object(
    'status', CASE WHEN v_risk_queued OR v_weekly_queued THEN 'queued'
                   WHEN v_seeded THEN 'seeded'
                   ELSE 'idle' END,
    'seeded', v_seeded,
    'risk_change_queued', v_risk_queued,
    'weekly_summary_queued', v_weekly_queued,
    'season_number', p_season_number
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.claim_chaos_clan_health_alerts(
  p_now bigint,
  p_limit integer DEFAULT 10,
  p_lease_ms integer DEFAULT 45000
)
RETURNS SETOF public.chaos_clan_health_alerts
LANGUAGE sql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $$
  WITH claimable AS (
    SELECT id
    FROM public.chaos_clan_health_alerts
    WHERE (
      (status IN ('pending', 'failed') AND next_attempt_at <= p_now)
      OR (status = 'sending' AND lease_until <= p_now)
    )
    ORDER BY created_at, id
    FOR UPDATE SKIP LOCKED
    LIMIT LEAST(GREATEST(COALESCE(p_limit, 10), 1), 30)
  )
  UPDATE public.chaos_clan_health_alerts AS alerts
  SET status = 'sending',
      attempt_count = alerts.attempt_count + 1,
      lease_until = p_now + LEAST(GREATEST(COALESCE(p_lease_ms, 45000), 10000), 120000),
      updated_at = p_now
  FROM claimable
  WHERE alerts.id = claimable.id
  RETURNING alerts.*;
$$;

CREATE OR REPLACE FUNCTION public.finish_chaos_clan_health_alert(
  p_id bigint,
  p_attempt_count integer,
  p_status text,
  p_now bigint,
  p_message_id text DEFAULT NULL,
  p_error text DEFAULT NULL,
  p_retry_at bigint DEFAULT 0
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_rows integer := 0;
BEGIN
  IF p_status NOT IN ('sent', 'failed') THEN
    RAISE EXCEPTION 'invalid clan health alert completion status';
  END IF;

  UPDATE public.chaos_clan_health_alerts
  SET status = p_status,
      discord_message_id = CASE WHEN p_status = 'sent' THEN p_message_id ELSE discord_message_id END,
      sent_at = CASE WHEN p_status = 'sent' THEN p_now ELSE sent_at END,
      last_error = CASE WHEN p_status = 'sent' THEN NULL ELSE left(COALESCE(p_error, 'delivery failed'), 500) END,
      next_attempt_at = CASE WHEN p_status = 'failed' THEN COALESCE(p_retry_at, p_now) ELSE next_attempt_at END,
      lease_until = 0,
      updated_at = p_now
  WHERE id = p_id
    AND status = 'sending'
    AND attempt_count = p_attempt_count;
  GET DIAGNOSTICS v_rows = ROW_COUNT;
  RETURN v_rows = 1;
END;
$$;

